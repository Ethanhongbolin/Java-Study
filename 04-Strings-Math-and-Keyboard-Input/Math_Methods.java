public class Math_Methods {
    public static void main(String[] args) {
        // Math methods

        System.out.println("Math.abs(-5): " + Math.abs(-5)); //absolute value
        System.out.println("Math.max(5, 10): " + Math.max(5, 10)); //maximum value
        System.out.println("Math.min(5, 10): " + Math.min(5, 10)); //minimum value
        System.out.println("Math.sqrt(25): " + Math.sqrt(25)); //square root
        System.out.println("Math.pow(2, 3): " + Math.pow(2, 3)); //power
        System.out.println("Math.round(5.6): " + Math.round(5.6)); //rounding
        System.out.println("Math.ceil(5.1): " + Math.ceil(5.1)); //rounding up
        System.out.println("Math.floor(5.9): " + Math.floor(5.9)); //rounding down
        System.out.println("Math.random(): " + Math.random()); //random number between 0 and 1
        System.out.println("Math.random() * 100: " + Math.random() * 100); //random number between 0 and 100
        System.out.println("Math.random() * 100 + 1: " + (Math.random() * 100 + 1)); //random number between 1 and 100
        System.out.println("Math.random() * 100 + 1: " + (int)(Math.random() * 100 + 1)); //random integer between 1 and 100
        System.out.println("Math.random() * 100 + 1: " + (int)(Math.random() * 100 +    1)); //random integer between 1 and 100
        System.out.println(Math.PI); //pi
        System.out.println(Math.E); //e

        

    }
}
