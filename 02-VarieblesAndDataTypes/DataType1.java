public class DataType1 {
    public static void main(String[] args) {
        System.out.println(123); //Integer
        System.out.println(0.125); //Floating Point Number
        System.out.println('A'); //Char
        System.out.println(true); //Boolean
        System.out.println("Hello, Java"); //String   
        

        // The following notes are creating variable with data type
        byte age = 100;
        int your_name = 20;
        String message = null;
        String message1 = " ";
        System.out.println();

        String ethan_Last_name = "Lin";
        System.out.println(ethan_Last_name);
        System.out.println(message);
        System.out.println(message1);
        
        System.out.println(age);
        System.out.println(your_name);
    }
}

